#!/usr/bin/env python3
"""Builds results/side_by_side.md from the compiler output saved by run_all.sh."""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"

# (case id, mistake, C-side form, what ThetOS does about it)
CASES = [
    ("wrong_mode", "Write to a pin configured as an input",
     "`HAL_GPIO_Init` as input, then `HAL_GPIO_WritePin`", "typestate: `set()` exists only on output pins"),
    ("stale_handle", "Reuse a handle after it changed state",
     "`HAL_UART_DeInit`, then `HAL_UART_Transmit` on the same handle", "ownership: the state change consumes the old handle"),
    ("uart_before_init", "Use a UART that was never initialised",
     "`HAL_UART_Transmit` with no `HAL_UART_Init`", "typestate: `write_byte()` exists only on an active UART"),
    ("pwm_before_active", "Use a PWM channel before the timer is activated",
     "`HAL_TIM_PWM_Start` with no `HAL_TIM_PWM_Init`", "typestate: `channel1()` exists only on an active PWM timer"),
    ("shared_state", "Two tasks share a plain variable",
     "plain `static unsigned short` written and read by two tasks", "language: a shared static must be `Sync` (Rust, not ThetOS design)"),
]


def read(path):
    p = Path(path)
    return p.read_text() if p.exists() else ""


def sh(cmd, cwd=None):
    try:
        return subprocess.run(cmd, shell=True, cwd=cwd, capture_output=True, text=True).stdout.strip()
    except Exception:
        return "unknown"


def thetos_cell(case):
    log = read(RES / "thetos" / f"{case}.fail.log")
    fail_exit = read(RES / "thetos" / f"{case}.fail.exit").strip()
    ok_exit = read(RES / "thetos" / f"{case}.ok.exit").strip()
    m = re.search(r"error\[(E\d+)\]: (.+)", log)
    if fail_exit != "0" and m and ok_exit == "0":
        msg = m.group(2)
        note = re.search(r"method not found in `([^`]+)`", log)
        state = f" (the type is `{note.group(1)}`)" if note else ""
        return f"does not compile: `{m.group(1)}` {msg}{state}; correct form compiles"
    return "UNEXPECTED (see results/thetos/)"


def freertos_cell(case):
    code = read(RES / "freertos" / f"{case}.exit").strip()
    log = read(RES / "freertos" / f"{case}.log")
    warns = len(re.findall(r"warning:", log))
    errs = len(re.findall(r"error:", log))
    if code == "0":
        return f"compiles ({warns} warnings, {errs} errors)"
    return f"does not compile ({errs} errors)" if code else "not run"


lock = read(ROOT / "thetos" / "Cargo.lock")
m = re.search(r'git\+https://github\.com/rullo24/ThetOS\?tag=([^#"]+)#([0-9a-f]+)', lock)
thetos_ver = f"{m.group(1)} ({m.group(2)[:10]})" if m else "unknown"


def git_ver(d):
    p = ROOT / "freertos" / d
    return sh("git describe --tags --always", cwd=p) + " (" + sh("git rev-parse --short=10 HEAD", cwd=p) + ")"


gcc = sh("arm-none-eabi-gcc --version | head -1")
rustc = sh("rustc --version", cwd=ROOT / "thetos")

out = []
out.append("# ThetOS vs FreeRTOS: compile-time comparison of the same mistakes\n")
out.append("Generated by `run_all.sh`. Each row is one mistake, written for a FreeRTOS firmware task and for a ThetOS task.\n")
out.append("**What is compared.** ThetOS ships typestate drivers as part of the framework. FreeRTOS ships no peripheral layer, "
           "so the realistic counterpart is FreeRTOS firmware using the vendor's STM32L1 HAL. The comparison is therefore of the "
           "two firmware stacks, not of the kernels alone.\n")
out.append("| Case | Mistake | FreeRTOS + STM32 HAL (C) | ThetOS (Rust) | Mechanism |")
out.append("|---|---|---|---|---|")
for case, mistake, cform, mech in CASES:
    out.append(f"| `{case}` | {mistake} ({cform}) | {freertos_cell(case)} | {thetos_cell(case)} | {mech} |")
out.append("")
out.append("Every ThetOS failure has a passing control (the `ok_*` fixture in `thetos/src/lib.rs`): the same operation in the correct state compiles.\n")
out.append("## Where ThetOS does not differ\n")
out.append("- Task arguments are type-erased in both (`void *` vs `*mut ()`).")
out.append("- Priority and stack-size checks are runtime checks in both.")
out.append("- Stack overflow is detected at runtime in both (FreeRTOS `configCHECK_FOR_STACK_OVERFLOW`, ThetOS canary guard).")
out.append("- Reusing one physical pin through two handles still compiles in ThetOS (ADR-0008).")
out.append("- The shared-state row comes from the Rust language, not from the ThetOS design.\n")
out.append("## Versions\n")
out.append(f"- ThetOS: {thetos_ver}")
out.append(f"- FreeRTOS-Kernel: {git_ver('FreeRTOS-Kernel')}")
out.append(f"- STM32L1 HAL driver: {git_ver('third_party/stm32l1xx_hal_driver')}")
out.append(f"- CMSIS device (L1): {git_ver('third_party/cmsis_device_l1')}")
out.append(f"- CMSIS core: {git_ver('third_party/cmsis_core')}")
out.append(f"- C compiler: {gcc} (flags: `-Wall -Wextra -std=c11 -mcpu=cortex-m3 -mthumb`)")
out.append(f"- Rust: {rustc} (`cargo check --target thumbv7m-none-eabi`)")
(RES / "side_by_side.md").write_text("\n".join(out) + "\n")
